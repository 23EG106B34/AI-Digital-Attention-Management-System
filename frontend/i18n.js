  const DICT = Object.assign({}, NAV, SHELL, DASHBOARD, GOALS, STATUS, PROMPTS);

  function getLang() {
    try {
      return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;
    }
  }

  function setLang(lang) {
    if (!LANGS.some(l => l.code === lang)) return;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    applyLang(lang);
    window.dispatchEvent(new CustomEvent('fg_lang_change', { detail: { lang } }));
  }

  function t(text) {
    if (!text || typeof text !== 'string') return text;
    const lang = getLang();
    if (lang === DEFAULT_LANG) return text;
    const idx = LANG_ORDER.indexOf(lang);
    if (idx === -1) return text;
    const clean = text.trim();
    if (DICT[clean] && DICT[clean][idx]) {
      return text.replace(clean, DICT[clean][idx]);
    }
    return text;
  }

  function applyLang(lang) {
    document.documentElement.setAttribute('lang', lang);
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = t(key);
      }
    });
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.setAttribute('placeholder', t(key));
      }
    });
  }

  window.fgI18n = {
    LANGS,
    getLang,
    setLang,
    t,
    applyLang,
  };

  document.addEventListener('DOMContentLoaded', () => {
    applyLang(getLang());
  });
